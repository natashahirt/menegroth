#!/usr/bin/env python3
"""Emit a CANDIDATES file (for corpus_locators.py) from the J10/K/L/M/N scribe.

The 2026-07-12 AISC batch was authored by ``scribe_aisc_j10_k_l_m_n.py``, which
stores its data as a ``CLAIMS`` dict (key -> existing note id) plus a flat
``QUOTE_SPECS`` list of ``(key, n, title, dim, clause, quote_text)`` tuples. This
transforms that into the ``CANDIDATES = [{key, source_page, quotes:[...]}]`` shape
that ``corpus_locators.py`` consumes, and also writes a ``key -> note_id`` map so
the computed locators can later be stamped onto the right existing notes.

Read-only w.r.t. the graph: it ``ast``-parses the scribe module (no execution,
no zettelkasten import), so it is safe to run alongside the live MCP server.
"""
from __future__ import annotations

import ast
import json
import os

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RUNNERS = os.path.join(REPO, "scripts", "runners")
SRC = os.path.join(RUNNERS, "scribe_aisc_j10_k_l_m_n.py")


def load_literal(path: str, name: str):
    tree = ast.parse(open(path, encoding="utf-8").read(), filename=path)
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == name for t in node.targets
        ):
            return ast.literal_eval(node.value)
    raise SystemExit(f"{name} not found in {path}")


def main() -> int:
    claims = load_literal(SRC, "CLAIMS")          # key -> note_id
    quote_specs = load_literal(SRC, "QUOTE_SPECS")  # (key, n, title, dim, clause, text)

    # Group quote texts + clause by claim key, preserving order.
    by_key: dict[str, dict] = {}
    for key, _n, _title, _dim, clause, text in quote_specs:
        rec = by_key.setdefault(key, {"quotes": [], "clause": clause})
        rec["quotes"].append(text)

    candidates = []
    for key in claims:  # claims order == document order (c5..c42)
        rec = by_key.get(key, {"quotes": [], "clause": ""})
        candidates.append(
            {"key": key, "source_page": rec.get("clause", ""), "quotes": rec["quotes"]}
        )

    # Emit a .py with a CANDIDATES literal for corpus_locators.py.
    out_py = os.path.join(RUNNERS, "_jklmn_candidates.py")
    with open(out_py, "w", encoding="utf-8") as f:
        f.write("# Auto-generated by build_jklmn_candidates.py — do not edit.\n")
        f.write("CANDIDATES = " + repr(candidates) + "\n")

    # Emit the key -> note_id map for the later stamping step.
    out_map = os.path.join(RUNNERS, "_jklmn_keymap.json")
    json.dump(claims, open(out_map, "w", encoding="utf-8"), indent=2)

    print(f"wrote {out_py}  ({len(candidates)} candidates, {sum(len(c['quotes']) for c in candidates)} quotes)")
    print(f"wrote {out_map}  ({len(claims)} claim ids)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
